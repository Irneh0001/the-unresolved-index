import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { approvedUpdates as existingUpdates } from "../data/research/approved-updates.js";

const queuePath = "data/research/candidates.generated.json";
const decisionsPath = "data/research/review-decisions/unresolved-index-review-decisions.json";
const updatesPath = "data/research/approved-updates.js";

export function parseReviewRequest(body) {
  const match = String(body ?? "").match(/<!--\s*unresolved-index-review:v1\s*([\s\S]*?)\s*-->/i);
  if (!match) throw new Error("Review request marker not found.");
  const payload = JSON.parse(match[1]);
  const decisions = payload.decisions ?? {};
  if (!decisions || typeof decisions !== "object" || Array.isArray(decisions)) throw new Error("Review decisions must be an object.");
  const entries = Object.entries(decisions).filter(([, decision]) => decision === "approved" || decision === "rejected");
  if (!entries.length) throw new Error("No approved or rejected decisions were submitted.");
  if (entries.length > 100) throw new Error("A review request may contain at most 100 decisions.");
  return { ...payload, decisions: Object.fromEntries(entries) };
}

export function applyReviewRequest({body, queue, reviewLedger, updates = [], now = new Date()} = {}) {
  const request = parseReviewRequest(body);
  const candidates = Array.isArray(queue.candidates) ? queue.candidates : [];
  const byId = new Map(candidates.map(candidate => [candidate.id, candidate]));
  const submittedIds = Object.keys(request.decisions);
  const missing = submittedIds.filter(id => !byId.has(id));
  if (missing.length) throw new Error(`Candidate IDs not present in the queue: ${missing.join(", ")}`);

  const applied = [];
  const nextUpdates = [...updates];
  for (const [candidateId, decision] of Object.entries(request.decisions)) {
    const candidate = byId.get(candidateId);
    if (decision !== "approved" || nextUpdates.some(update => update.candidate_id === candidateId)) continue;
    const suffix = createHash("sha256").update(candidateId).digest("hex").slice(0, 12);
    const sourceId = `src-reviewed-${suffix}`;
    const eventId = `evt-reviewed-${suffix}`;
    const appliedAt = now.toISOString();
    const date = parseDate(candidate.published_at) ?? appliedAt.slice(0, 10);
    nextUpdates.push({
      candidate_id: candidateId,
      applied_at: appliedAt,
      source: {
        id: sourceId,
        title: candidate.title,
        publisher: `Configured discovery feed (${candidate.source_id})`,
        url: candidate.url,
        published_at: candidate.published_at ?? null,
        retrieved_at: appliedAt.slice(0, 10),
        source_class: "candidate_feed",
        authority_level: 1,
        country: "United States",
        domains: [],
        reliability_notes: "Candidate source retained after human approval; publisher authority and the underlying report require separate evaluation.",
        supports_claims: [],
        contradicts_claims: []
      },
      event: {
        id: eventId,
        topic_id: candidate.topic_id,
        date,
        title: candidate.title,
        description: `Source-reported update retained after human approval: ${candidate.summary || "No excerpt was supplied."}`,
        event_type: "reviewed_source_update",
        importance: 50,
        source_ids: [sourceId],
        materiality: "context"
      }
    });
    applied.push(candidateId);
  }

  const decisionsOut = {...(reviewLedger.decisions ?? {}), ...request.decisions};
  return {
    applied,
    updates: nextUpdates,
    queue: {
      ...queue,
      checked_at: now.toISOString(),
      candidates: candidates.filter(candidate => !submittedIds.includes(candidate.id))
    },
    reviewLedger: {
      exported_at: now.toISOString(),
      decisions: decisionsOut
    }
  };
}

function parseDate(value) {
  if (!value) return null;
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? null : parsed.toISOString().slice(0, 10);
}

if (process.argv[1]?.endsWith("apply-approved-candidates.mjs")) {
  const body = process.env.REVIEW_BODY;
  const [queue, reviewLedger] = await Promise.all([
    readJson(queuePath, {candidates: []}),
    readJson(decisionsPath, {decisions: {}})
  ]);
  const result = applyReviewRequest({body, queue, reviewLedger, updates: existingUpdates});
  await writeFile(queuePath, JSON.stringify(result.queue, null, 2) + "\n");
  await writeFile(decisionsPath, JSON.stringify(result.reviewLedger, null, 2) + "\n");
  await writeFile(updatesPath, `// Generated by the reviewed-update workflow. Each record is created from an approved candidate.\nexport const approvedUpdates = ${JSON.stringify(result.updates, null, 2)};\n`);
  console.log(JSON.stringify({applied: result.applied, remaining_candidates: result.queue.candidates.length}));
}

async function readJson(path, fallback) {
  try { return JSON.parse(await readFile(path, "utf8")); }
  catch (error) {
    if (error.code === "ENOENT") return fallback;
    throw error;
  }
}
